import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { CoverageMarkdown } from './coverage-markdown.ts';
import { MarkdownTools } from './markdown.ts';
import { SnippetLibrary } from './snippets.ts';

const NOTE = '<!-- Generated by `npm run llm:build` from docs/llm and docs/examples/llm-usage.ts. Do not edit. -->';

/** Generates `llm/USAGE.md` and `skills/postgrelize/**` from templates and tested example regions. */
export class LlmAssetBuilder {
  readonly #root: string;
  readonly #markdown: MarkdownTools;
  readonly #coverage = new CoverageMarkdown();

  constructor(repositoryRoot: string) {
    this.#root = repositoryRoot;
    this.#markdown = new MarkdownTools(new SnippetLibrary(join(repositoryRoot, 'docs/examples')));
  }

  /** Map of repository-relative output path to file content. */
  build(): Map<string, string> {
    const templates = join(this.#root, 'docs/llm');
    const out = new Map<string, string>();
    for (const file of LlmAssetBuilder.#markdownFiles(templates)) {
      out.set(this.#target(relative(templates, file)), this.#render(readFileSync(file, 'utf8')));
    }
    return out;
  }

  /** Writes every generated file under the repository root. */
  write(): void {
    for (const [path, content] of this.build()) {
      const absolute = join(this.#root, path);
      mkdirSync(dirname(absolute), { recursive: true });
      writeFileSync(absolute, content);
    }
  }

  #target(template: string): string {
    return template.startsWith('skill/')
      ? join('skills/postgrelize', template.slice('skill/'.length))
      : join('llm', template);
  }

  #render(template: string): string {
    const body = this.#markdown
      .inlineSnippets(template)
      .replace('{{unsupported}}', this.#coverage.unsupported());
    const front = /^---\n[\s\S]*?\n---\n/.exec(body)?.[0] ?? '';
    return `${front}${NOTE}\n${body.slice(front.length).trimStart()}`.trimEnd() + '\n';
  }

  static #markdownFiles(directory: string): string[] {
    return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) {
        return LlmAssetBuilder.#markdownFiles(path);
      }
      return entry.name.endsWith('.md') ? [path] : [];
    });
  }
}
