import { describe, it } from 'vitest';
import { expectSameResult } from '../support/compat.ts';

type Entry = Record<string, unknown> & { type: { constructor: { key: string; name: string } } };

describe('compat: shape of getAttributes()', () => {
  it('reports the type class, the model and the attribute flag like v6', () =>
    expectSameResult('', async (lib, sequelize) => {
      const { DataTypes } = lib;
      const User = sequelize.define('User', {
        username: DataTypes.STRING,
        nick: DataTypes.STRING(20),
        age: { type: DataTypes.BIGINT },
        active: DataTypes.BOOLEAN,
      });
      const attributes = User.getAttributes() as unknown as Record<string, Entry>;
      return Object.entries(attributes).map(([name, entry]) => [
        name,
        entry.type.constructor.key,
        entry['Model'] === User,
        entry['_modelAttribute'],
        entry['fieldName'],
        entry['field'],
        entry['_autoGenerated'] ?? false,
      ]);
    }));
});
