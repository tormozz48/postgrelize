import { promisify } from 'node:util';
import { ValidationErrorItem } from '../errors/errors.ts';
import { SqlExpression } from '../expressions/methods.ts';
import type { AttributeDefinition, ModelDefinition } from '../model/definition.ts';
import { BuiltinValidators } from './builtin-validators.ts';
import type { StandardSchemaV1 } from './standard-schema.ts';
import { StandardSchemaValidator } from './standard-schema-validator.ts';
import type {
  AttributeValidateOptions,
  AttributeValidatorFunction,
  ModelValidatorFunction,
} from './types.ts';

/** Data needed to validate one instance. */
export type ValidationTarget = Readonly<{
  instance: object;
  definition: ModelDefinition;
  values: Readonly<Record<string, unknown>>;
  previous: Readonly<Record<string, unknown>>;
  isNewRecord: boolean;
}>;

/** Which attributes / model validators to skip. */
export type ValidationScope = Readonly<{ skip: ReadonlySet<string> }>;

const STRING_TYPES: ReadonlySet<string> = new Set(['STRING', 'TEXT', 'CITEXT', 'CHAR']);

const builtinValidators = new BuiltinValidators();

const standardSchema = new StandardSchemaValidator();

const isNullish = (value: unknown): value is null | undefined =>
  value === null || value === undefined;

/**
 * Validates instances like Sequelize v6 `InstanceValidator` (without hooks): `notNull`, string
 * values, built-in (validator.js) and custom attribute validators, Standard Schemas and model
 * validators. Expressions (`literal`, `fn`, ...) are not validated.
 *
 * @internal
 */
export class InstanceValidator {
  /**
   * Validates an instance and returns all failures.
   *
   * @param target - Instance, its definition and values.
   * @param scope - Attributes and model validators to skip.
   * @param modelValidators - Model-level validators (`validate` model option).
   * @param modelSchema - Standard Schema of the whole model (`schema` model option).
   * @returns Failures; empty when the instance is valid.
   */
  async validate(
    target: ValidationTarget,
    scope: ValidationScope,
    modelValidators: Readonly<Record<string, ModelValidatorFunction>> = {},
    modelSchema?: StandardSchemaV1,
  ): Promise<readonly ValidationErrorItem[]> {
    const attributes = [...target.definition.attributes.values()].filter(
      (attribute) =>
        !scope.skip.has(attribute.fieldName) &&
        !(target.values[attribute.fieldName] instanceof SqlExpression),
    );
    const schemaErrors = attributes.flatMap((attribute) =>
      this.#schemaItems(target.definition, target, attribute, target.values[attribute.fieldName]),
    );
    const [attributeErrors, modelErrors, schemaIssues] = await Promise.all([
      Promise.all(
        attributes.map((attribute) =>
          this.#attributeValidatorItems(target, attribute, target.values[attribute.fieldName]),
        ),
      ),
      this.#modelValidatorItems(target, modelValidators, scope),
      modelSchema === undefined
        ? Promise.resolve([])
        : this.#schemaValidatorItems(target, modelSchema, this.#plainValues(target), undefined),
    ]);
    return [...schemaErrors, ...attributeErrors.flat(), ...modelErrors, ...schemaIssues];
  }

  #messageOf(error: unknown): string {
    return error instanceof Error
      ? error.message
      : typeof error === 'string' && error !== ''
        ? error
        : 'Validation error';
  }

  #schemaItems(
    definition: ModelDefinition,
    target: ValidationTarget,
    attribute: AttributeDefinition,
    value: unknown,
  ): readonly ValidationErrorItem[] {
    if (attribute._autoGenerated === true || attribute.autoIncrement === true) {
      return [];
    }
    if (attribute.allowNull === false && isNullish(value)) {
      const notNull = (attribute.validate as AttributeValidateOptions | undefined)?.notNull;
      const message =
        typeof notNull === 'object' && notNull.msg !== undefined
          ? notNull.msg
          : `${definition.name}.${attribute.fieldName} cannot be null`;
      return [
        new ValidationErrorItem(
          message,
          'notNull Violation',
          attribute.fieldName,
          value,
          target.instance,
          'is_null',
        ),
      ];
    }
    if (
      STRING_TYPES.has(attribute.type.key) &&
      typeof value === 'object' &&
      value !== null &&
      !Buffer.isBuffer(value) &&
      !(value instanceof SqlExpression)
    ) {
      return [
        new ValidationErrorItem(
          `${attribute.fieldName} cannot be an array or an object`,
          'string violation',
          attribute.fieldName,
          value,
          target.instance,
          'not_a_string',
        ),
      ];
    }
    return [];
  }

  async #callCustom(
    instance: object,
    fn: (...args: never[]) => unknown,
    args: readonly unknown[],
  ): Promise<void> {
    if (fn.length === args.length + 1) {
      await promisify((fn as (...callArgs: unknown[]) => unknown).bind(instance, ...args))();
      return;
    }
    await (fn as (...callArgs: unknown[]) => unknown).apply(instance, [...args]);
  }

  #validatorArgs(
    test: unknown,
    name: string,
    field: string,
    target: ValidationTarget,
  ): readonly unknown[] {
    const raw =
      typeof test === 'object' && test !== null && 'args' in test
        ? (test as { args: unknown }).args
        : test;
    if (Array.isArray(raw)) {
      return raw;
    }
    if (name === 'isImmutable') {
      return [raw, field, target];
    }
    return (typeof raw !== 'string' &&
      ['isAlpha', 'isAlphanumeric', 'isMobilePhone'].includes(name)) ||
      name === 'isIP'
      ? []
      : [raw];
  }

  #customMessage(test: unknown): string | undefined {
    return typeof test === 'object' && test !== null && 'msg' in test
      ? String((test as { msg: unknown }).msg)
      : undefined;
  }

  #runBuiltin(
    target: ValidationTarget,
    attribute: AttributeDefinition,
    name: string,
    test: unknown,
    value: unknown,
  ): ValidationErrorItem | undefined {
    if (test === false) {
      return undefined;
    }
    const field = attribute.fieldName;
    const normalized = ['isUrl', 'isURL', 'isEmail'].includes(name)
      ? this.#customMessage(test) === undefined
        ? {}
        : { msg: this.#customMessage(test) }
      : test;
    const args = this.#validatorArgs(normalized, name, field, target);
    const passed =
      name === 'isImmutable'
        ? target.isNewRecord || target.values[field] === target.previous[field]
        : (() => {
            const fn = builtinValidators.find(name);
            if (fn === undefined) {
              throw new Error(`Invalid validator function: ${name}`);
            }
            return fn(String(value), ...args);
          })();
    return passed
      ? undefined
      : new ValidationErrorItem(
          this.#customMessage(normalized) ?? `Validation ${name} on ${field} failed`,
          'Validation error',
          field,
          value,
          target.instance,
          name,
          name,
          args,
        );
  }

  async #schemaValidatorItems(
    target: ValidationTarget,
    schema: StandardSchemaV1,
    value: unknown,
    path: string | undefined,
  ): Promise<readonly ValidationErrorItem[]> {
    return (await standardSchema.issues(schema, value)).map(
      (issue) =>
        new ValidationErrorItem(
          issue.message,
          'Validation error',
          path === undefined
            ? (issue.path ?? null)
            : issue.path === undefined
              ? path
              : `${path}.${issue.path}`,
          value,
          target.instance,
          'schema',
        ),
    );
  }

  async #attributeValidatorItems(
    target: ValidationTarget,
    attribute: AttributeDefinition,
    value: unknown,
  ): Promise<readonly ValidationErrorItem[]> {
    const validate = (attribute.validate ?? {}) as AttributeValidateOptions;
    if (isNullish(value) && attribute.allowNull === false) {
      return [];
    }
    const results = await Promise.all(
      Object.entries(validate)
        .filter(([name]) => name !== 'notNull')
        .map(async ([name, test]): Promise<readonly ValidationErrorItem[]> => {
          if (name === 'schema' && standardSchema.isSchema(test)) {
            return value === undefined
              ? []
              : this.#schemaValidatorItems(target, test, value, attribute.fieldName);
          }
          if (typeof test === 'function') {
            try {
              await this.#callCustom(target.instance, test as AttributeValidatorFunction, [value]);
              return [];
            } catch (error) {
              return [
                new ValidationErrorItem(
                  this.#messageOf(error),
                  'Validation error',
                  attribute.fieldName,
                  value,
                  target.instance,
                  name,
                ),
              ];
            }
          }
          if (isNullish(value)) {
            return [];
          }
          const item = this.#runBuiltin(target, attribute, name, test, value);
          return item === undefined ? [] : [item];
        }),
    );
    return results.flat();
  }

  async #modelValidatorItems(
    target: ValidationTarget,
    validators: Readonly<Record<string, ModelValidatorFunction>>,
    scope: ValidationScope,
  ): Promise<readonly ValidationErrorItem[]> {
    const results = await Promise.all(
      Object.entries(validators)
        .filter(([name]) => !scope.skip.has(name))
        .map(async ([name, fn]): Promise<readonly ValidationErrorItem[]> => {
          try {
            await this.#callCustom(target.instance, fn, []);
            return [];
          } catch (error) {
            return [
              new ValidationErrorItem(
                this.#messageOf(error),
                'Validation error',
                name,
                null,
                target.instance,
                name,
              ),
            ];
          }
        }),
    );
    return results.flat();
  }

  #plainValues(target: ValidationTarget): Readonly<Record<string, unknown>> {
    return Object.fromEntries(
      [...target.definition.attributes.keys()].map((name) => [name, target.values[name]]),
    );
  }
}
