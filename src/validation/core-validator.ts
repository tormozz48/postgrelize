import { ValidationErrorItem } from '../errors/errors.ts';
import { SqlExpression } from '../expressions/methods.ts';
import type { AttributeDefinition } from '../model/model-definition.ts';
import type { AttributeValidateOptions } from './types.ts';
import type { ValidationTarget } from './validation-target.ts';

const STRING_TYPES: ReadonlySet<string> = new Set(['STRING', 'TEXT', 'CITEXT', 'CHAR']);

/** Checks the checks Sequelize v6 always runs: `allowNull` and string attributes holding objects. */
export class CoreValidator {
  /**
   * Validates one attribute value.
   *
   * @param target - Instance being validated.
   * @param attribute - Attribute definition.
   * @param value - Current value of the attribute.
   * @returns Failures; empty for auto-generated attributes and valid values.
   */
  items(
    target: ValidationTarget,
    attribute: AttributeDefinition,
    value: unknown,
  ): readonly ValidationErrorItem[] {
    if (attribute._autoGenerated === true || attribute.autoIncrement === true) {
      return [];
    }
    const item =
      this.#notNull(target, attribute, value) ?? this.#notString(target, attribute, value);
    return item === undefined ? [] : [item];
  }

  #notNull(
    target: ValidationTarget,
    attribute: AttributeDefinition,
    value: unknown,
  ): ValidationErrorItem | undefined {
    if (attribute.allowNull !== false || (value !== null && value !== undefined)) {
      return undefined;
    }
    const message = CoreValidator.#notNullMessage(target, attribute);
    return new ValidationErrorItem(
      message,
      'notNull Violation',
      attribute.fieldName,
      value,
      target.instance,
      'is_null',
    );
  }

  static #notNullMessage(target: ValidationTarget, attribute: AttributeDefinition): string {
    const notNull = (attribute.validate as AttributeValidateOptions | undefined)?.notNull;
    return typeof notNull === 'object' && notNull.msg !== undefined
      ? notNull.msg
      : `${target.definition.name}.${attribute.fieldName} cannot be null`;
  }

  #notString(
    target: ValidationTarget,
    attribute: AttributeDefinition,
    value: unknown,
  ): ValidationErrorItem | undefined {
    if (!STRING_TYPES.has(attribute.type.key) || !CoreValidator.#isStructured(value)) {
      return undefined;
    }
    return new ValidationErrorItem(
      `${attribute.fieldName} cannot be an array or an object`,
      'string violation',
      attribute.fieldName,
      value,
      target.instance,
      'not_a_string',
    );
  }

  static #isStructured(value: unknown): boolean {
    return (
      typeof value === 'object' &&
      value !== null &&
      !Buffer.isBuffer(value) &&
      !(value instanceof SqlExpression)
    );
  }
}
