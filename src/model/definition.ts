import inflection from 'inflection';
import {
  DataTypes,
  toDataType,
  type DataType,
  type DataTypeInput,
} from '../data-types/data-types.ts';
import type { ModelDefaults } from '../connection/options.ts';

/** Named unique constraint of an attribute. */
export type UniqueOptions = Readonly<{
  /** Constraint name; attributes with the same name form a composite unique key. */
  name?: string;
  /** Validation message used when the constraint is violated. */
  msg?: string;
}>;

/** Table referenced by a foreign key. */
export type ReferencedTable = Readonly<{
  /** Referenced table name. */
  tableName: string;
}>;

/** Foreign key target of an attribute. */
export type ReferenceOptions = Readonly<{
  /** Referenced model name, or an object with the referenced table name. */
  model: string | ReferencedTable;
  /** Referenced column. Default: primary key. */
  key?: string;
}>;

/** Column definition of a model attribute (Sequelize v6 `ModelAttributeColumnOptions`). */
export type AttributeOptions = Readonly<{
  /** Column type. */
  type: DataTypeInput;
  /** Whether `NULL` is allowed. Default true. */
  allowNull?: boolean;
  /** Default value: a literal value, an expression, or `DataTypes.NOW` / `DataTypes.UUIDV4`. */
  defaultValue?: unknown;
  /** Part of the primary key. */
  primaryKey?: boolean;
  /** Generated by a sequence (`SERIAL`). */
  autoIncrement?: boolean;
  /** Column name, if different from the attribute name. */
  field?: string;
  /** Unique constraint: `true`, a constraint name, or `{ name, msg }`. */
  unique?: boolean | string | UniqueOptions;
  /** Column comment. */
  comment?: string;
  /** Foreign key reference. */
  references?: string | ReferenceOptions;
  /** `ON DELETE` action of the foreign key. */
  onDelete?: string;
  /** `ON UPDATE` action of the foreign key. */
  onUpdate?: string;
  /** Custom getter, called with the model instance as `this`. */
  get?: (this: never) => unknown;
  /** Custom setter, called with the model instance as `this`. */
  set?: (this: never, value: never) => void;
}>;

/** Attributes passed to `Model.init` / `sequelize.define`: a type or full column options per attribute. */
export type ModelAttributes = Readonly<Record<string, DataTypeInput | AttributeOptions>>;

/** Normalized attribute (exposed as `Model.rawAttributes[name]`). */
export type AttributeDefinition = Readonly<
  Omit<AttributeOptions, 'type' | 'field'> & {
    /** Attribute name. */
    fieldName: string;
    /** Column name. */
    field: string;
    /** Normalized column type. */
    type: DataType;
    /** Whether `NULL` is allowed. */
    allowNull: boolean;
    /** Added automatically (`id`, timestamps). */
    _autoGenerated?: boolean;
  }
>;

/** Table-level model options shared by `Model.init` and `sequelize.define`. */
export type DefinitionOptions = ModelDefaults &
  Readonly<{
    /** Model name. Defaults to the class name. */
    modelName?: string;
    /** Table name. Defaults to the pluralized model name. */
    tableName?: string;
    /** Name of the created-at attribute, or `false` to disable it. */
    createdAt?: string | boolean;
    /** Name of the updated-at attribute, or `false` to disable it. */
    updatedAt?: string | boolean;
  }>;

/** Immutable normalized model definition. */
export type ModelDefinition = Readonly<{
  name: string;
  tableName: string;
  schema: string | undefined;
  attributes: ReadonlyMap<string, AttributeDefinition>;
  fieldToAttribute: ReadonlyMap<string, string>;
  primaryKeys: readonly string[];
  createdAt: string | undefined;
  updatedAt: string | undefined;
  options: DefinitionOptions;
}>;

const isAttributeOptions = (value: DataTypeInput | AttributeOptions): value is AttributeOptions =>
  typeof value === 'object' && 'type' in value && typeof value.type !== 'string';

const timestampName = (
  option: string | boolean | undefined,
  fallback: string,
): string | undefined =>
  option === false ? undefined : typeof option === 'string' ? option : fallback;

const underscoredIf = (name: string, underscored: boolean): string =>
  underscored ? inflection.underscore(name) : name;

const normalizeAttribute = (
  name: string,
  input: DataTypeInput | AttributeOptions,
  underscored: boolean,
): AttributeDefinition => {
  const options: AttributeOptions = isAttributeOptions(input) ? input : { type: input };
  const { type, field, ...rest } = options;
  return Object.freeze({
    ...rest,
    fieldName: name,
    field: field ?? underscoredIf(name, underscored),
    type: toDataType(type),
    allowNull: options.allowNull ?? options.primaryKey !== true,
  });
};

const autoPrimaryKey = (attributes: ModelAttributes, tableName: string): ModelAttributes => {
  const entries = Object.values(attributes);
  if (entries.some((value) => isAttributeOptions(value) && value.primaryKey === true)) {
    return {};
  }
  if ('id' in attributes) {
    throw new Error(
      `A column called 'id' was added to the attributes of '${tableName}' but not marked with 'primaryKey: true'`,
    );
  }
  return {
    id: { type: DataTypes.INTEGER, allowNull: false, primaryKey: true, autoIncrement: true },
  };
};

const timestampAttributes = (
  createdAt: string | undefined,
  updatedAt: string | undefined,
): ModelAttributes =>
  Object.fromEntries(
    [createdAt, updatedAt]
      .filter((name): name is string => name !== undefined)
      .map((name) => [name, { type: DataTypes.DATE, allowNull: false }]),
  );

/** Normalizes `Model.init` arguments into an immutable definition, applying Sequelize v6 defaults. */
export const normalizeDefinition = (
  className: string,
  attributes: ModelAttributes,
  options: DefinitionOptions,
  defaults: ModelDefaults = {},
): ModelDefinition => {
  const merged: DefinitionOptions = { timestamps: true, ...defaults, ...options };
  const name = merged.modelName ?? className;
  const underscored = merged.underscored === true;
  const tableName =
    merged.tableName ??
    (merged.freezeTableName === true
      ? name
      : underscoredIf(inflection.pluralize(name), underscored));
  const createdAt =
    merged.timestamps === true ? timestampName(merged.createdAt, 'createdAt') : undefined;
  const updatedAt =
    merged.timestamps === true ? timestampName(merged.updatedAt, 'updatedAt') : undefined;
  const generated = new Set([
    ...Object.keys(autoPrimaryKey(attributes, tableName)),
    createdAt,
    updatedAt,
  ]);
  const all: ModelAttributes = {
    ...autoPrimaryKey(attributes, tableName),
    ...attributes,
    ...timestampAttributes(createdAt, updatedAt),
  };
  const normalized = new Map(
    Object.entries(all).map(([attribute, input]) => {
      const definition = normalizeAttribute(attribute, input, underscored);
      return [
        attribute,
        generated.has(attribute) && !(attribute in attributes)
          ? Object.freeze({ ...definition, _autoGenerated: true })
          : definition,
      ] as const;
    }),
  );
  return Object.freeze({
    name,
    tableName,
    schema: merged.schema,
    attributes: normalized,
    fieldToAttribute: new Map(
      [...normalized.values()].map((attribute) => [attribute.field, attribute.fieldName]),
    ),
    primaryKeys: [...normalized.values()]
      .filter((attribute) => attribute.primaryKey === true)
      .map((attribute) => attribute.fieldName),
    createdAt,
    updatedAt,
    options: merged,
  });
};
