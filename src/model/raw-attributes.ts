import type { ModelAttributes } from './attribute-options.ts';
import type { ModelDefinition } from './model-definition.ts';
import type { ModelState } from './model-state.ts';

type Entries = Record<string, Record<string, unknown>>;

// fields v6 adds to its entries; they are not part of the declaration
const ADDED: ReadonlySet<string> = new Set(['Model', '_modelAttribute']);

/**
 * The mutable `Model.rawAttributes` object of Sequelize v6: one copy of the attributes per
 * definition. Entries the application adds, changes or deletes are carried into the `init` input
 * when the definition is rebuilt (`refreshAttributes`, associations, `removeAttribute`).
 *
 * @internal
 */
export class RawAttributes {
  readonly #copies = new WeakMap<ModelDefinition, Entries>();

  of(definition: ModelDefinition, model: object): Entries {
    const existing = this.#copies.get(definition);
    if (existing !== undefined) {
      return existing;
    }
    const copy = Object.fromEntries(
      [...definition.attributes].map(([name, attribute]) => [
        name,
        { ...attribute, Model: model, _modelAttribute: true },
      ]),
    );
    this.#copies.set(definition, copy);
    return copy;
  }

  // the state with the application's changes to the copy applied to its `init` input
  apply(state: ModelState): ModelState {
    const copy = this.#copies.get(state.definition);
    if (copy === undefined) {
      return state;
    }
    const attributes: Record<string, unknown> = { ...state.input.attributes };
    const extra: Record<string, unknown> = { ...state.input.extra };
    this.#drop(state.definition, copy, [attributes, extra]);
    this.#adopt(state.definition, copy, attributes);
    const input = { ...state.input, attributes, extra };
    return { ...state, input: input as ModelState['input'] & { attributes: ModelAttributes } };
  }

  #drop(definition: ModelDefinition, copy: Entries, inputs: Record<string, unknown>[]): void {
    for (const name of definition.attributes.keys()) {
      if (!Object.hasOwn(copy, name)) {
        inputs.forEach((input) => delete input[name]);
      }
    }
  }

  #adopt(definition: ModelDefinition, copy: Entries, attributes: Record<string, unknown>): void {
    Object.entries(copy)
      .filter(([name, entry]) => this.#changed(definition, name, entry))
      .forEach(([name, entry]) => {
        const {
          _autoGenerated: _generated,
          Model: _model,
          _modelAttribute: _flag,
          ...declared
        } = entry;
        attributes[name] = declared;
      });
  }

  #changed(definition: ModelDefinition, name: string, entry: object): boolean {
    const original = definition.attributes.get(name) as Record<string, unknown> | undefined;
    const keys = Object.keys({ ...original, ...entry });
    return (
      original === undefined ||
      keys.some(
        (key) => !ADDED.has(key) && (entry as Record<string, unknown>)[key] !== original[key],
      )
    );
  }
}
